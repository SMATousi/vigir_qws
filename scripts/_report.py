"""Shared helpers for the results scripts: Markdown tables, report writing, and the
results index (results/README.md), which merges the headlines of every report."""

from __future__ import annotations

import datetime as dt
import json
import platform
from importlib import metadata
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[1] / "results"
RAW = OUT / "raw"
HEADLINES = RAW / "headlines.json"


def table(headers: list[str], rows: list[list]) -> str:
    def fmt(v):
        if isinstance(v, (bool, np.bool_)):
            return "yes" if v else "no"
        if isinstance(v, (float, np.floating)):
            v = float(v)
            if np.isnan(v):
                return "–"
            if np.isinf(v):
                return "∞"
            return f"{v:.3g}" if abs(v) < 1e-3 or abs(v) >= 1e4 else f"{v:.3f}"
        return str(v)

    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def ms(values) -> str:
    v = np.asarray(values, dtype=float)
    return f"{v.mean():.3f} ± {v.std(ddof=1) if v.size > 1 else 0.0:.3f}"


def write(name: str, title: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(f"# {title}\n\n{body.strip()}\n")
    print(f"wrote results/{name}")


def env_block() -> str:
    pkgs = ["numpy", "scipy", "scikit-image", "PyMaxflow", "dimod", "dwave-neal", "dwave-system", "minorminer",
            "qiskit", "qiskit-aer", "qiskit-ibm-runtime", "torch"]
    vers = []
    for p in pkgs:
        try:
            vers.append(f"{p} {metadata.version(p)}")
        except metadata.PackageNotFoundError:
            vers.append(f"{p} (not installed)")
    return (f"- Generated: {dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}\n"
            f"- Python {platform.python_version()} on {platform.machine()} ({platform.system()})\n"
            f"- Packages: {', '.join(vers)}\n"
            f"- Hardware: CPU only. **No real QPU was used.** `anneal_sim` is D-Wave Ocean's classical "
            f"`SimulatedAnnealingSampler`; `anneal_mock` is `MockDWaveSampler` with a Pegasus topology "
            f"and a fixed-temperature simulated-annealing substitute.")


def register(entries: dict[str, dict[str, str]]) -> None:
    """Record report headlines: {file: {"title", "question", "headline"}}."""
    RAW.mkdir(parents=True, exist_ok=True)
    data = json.loads(HEADLINES.read_text()) if HEADLINES.exists() else {}
    data.update(entries)
    HEADLINES.write_text(json.dumps(data, indent=2))


def write_index() -> None:
    data = json.loads(HEADLINES.read_text()) if HEADLINES.exists() else {}
    rows = "\n".join(f"| [{v['title']}]({k}) | {v['question']} | {v['headline']} |" for k, v in sorted(data.items()))
    body = f"""
Detailed results for `qws`. Every report is regenerated by two scripts:

```bash
python scripts/generate_results.py             # reports 01–04 (~4 min)
python scripts/generate_results_extensions.py  # reports 05–10 (~15 min)
# both accept --quick for smaller settings
```

Raw numbers are in [`raw/`](raw/). Design decisions and implementation details behind every number are in
[`spec/09-implementation-notes.md`](../spec/09-implementation-notes.md) and
[`spec/10-decision-log.md`](../spec/10-decision-log.md).

## Environment (last run)

{env_block()}

## Reports

| Report | Question | Headline |
|--------|----------|----------|
{rows}

## Scope and caveats

- **No real quantum hardware was used.** Quantum paths ran on simulators and mocks (see Environment).
  Hardware runs are roadmap Phase 3 ([spec/08](../spec/08-roadmap.md)) and need a D-Wave Leap token and an
  IBM Quantum account.
- **No real images were used.** The Oxford-IIIT Pet hosts are blocked by this environment's network
  policy. Reports 08–09 use a generated dataset in the exact Pet file layout to exercise the real-image
  pipeline; they are not Pet results.
- **Synthetic votes** in reports 01–07 follow the label model's own generative law, which is a best case.
- **Timings are CPU wall-clock times** on a shared cloud container. They are indicative only.
"""
    write("README.md", "Results", body)
